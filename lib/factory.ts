// Fábrica que gera em lote e salva em /music-base/{genre}/

import { generateWithFreeFirst } from './factory-router';
import crypto from 'crypto';

export async function generateBatch(genre: string, total: number, bpmRange = [80, 95]) {
  const results = [];
  for (let i = 1; i <= total; i++) {
    const id = `ssl-${genre}-${String(i).padStart(3, '0')}`;
    const bpm = Math.floor(Math.random() * (bpmRange[1] - bpmRange[0])) + bpmRange[0];
    const prompt = `royalty-free ${genre} ${bpm}bpm, original ${genre} track, ${genre} instruments, no vocals copyrighted, clean master`;

    console.log(`[Factory] Gerando ${id} (${i}/${total})`);

    const { audioUrl, modelUsed, isFree } = await generateWithFreeFirst(prompt, 120);

    // Gerar hash e JSON certificado ECAD-free
    const hash = crypto.createHash('sha256').update(`${id}${prompt}${Date.now()}`).digest('hex');
    const metadata = {
      id,
      genre,
      bpm,
      prompt,
      model: modelUsed,
      isFree,
      license: 'royalty-free, ECAD-free, commercial use allowed, no author rights, generated by AI',
      filePath: `/music-base/${genre}/${id}.mp3`,
      jsonPath: `/music-base/${genre}/${id}.json`,
      hash,
      generated_at: new Date().toISOString(),
      owner: 'SpectraSoundLab',
    };

    // TODO: Salvar audioUrl em Storage em /music-base/{genre}/{id}.mp3
    // TODO: Salvar metadata em /music-base/{genre}/{id}.json
    // TODO: Salvar doc em Firestore tracks

    results.push(metadata);
  }
  return results;
}
